"""Evidence-grounded incident investigation."""

from app.agentops.simulator import latency_spike_scenario


def investigate_incident() -> dict:
    scenario = latency_spike_scenario()
    evidence_ids = {item["id"] for item in scenario["evidence"]}

    # Fail closed if a diagnosis references evidence that was not collected.
    for hypothesis in scenario["hypotheses"]:
        if not set(hypothesis["evidence_ids"]).issubset(evidence_ids):
            raise RuntimeError("Hypothesis references missing evidence")

    ranked = sorted(
        scenario["hypotheses"],
        key=lambda item: item["confidence"],
        reverse=True,
    )

    return {
        "scenario_id": scenario["scenario_id"],
        "service": scenario["service"],
        "signal": scenario["signal"],
        "evidence": scenario["evidence"],
        "hypotheses": ranked,
        "leading_hypothesis": ranked[0],
        "proposed_action": scenario["proposed_action"],
        "limitations": [
            "Evidence is generated by a deterministic simulator, not live infrastructure.",
            "Confidence scores are scenario-defined test values, not calibrated probabilities.",
            "A simulated recovery does not establish that the same action would fix a real incident.",
        ],
    }
